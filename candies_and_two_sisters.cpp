#include <iostream>
#include <vector>

int main() {
  int n{};
  std::cin >> n;

  std::vector<int> nums{};
  while(n--) {
    std::cin >> nums.emplace_back();
  }

  for (auto i : nums) {
    if (i == 0 || i == 1) {
      std::cout << 0 << '\n';
      continue;
    }
    std::cout << i - i / 2 - 1 << '\n';
  }

  return 0;
}
